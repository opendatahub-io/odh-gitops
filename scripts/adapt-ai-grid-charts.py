#!/usr/bin/env python3
"""Expose vendored runtime templates for profile-aware rendering by the parent.

Standalone installs still render normally. When used as dependencies, resources
are emitted only by the parent's management-state gate. No shared Values mutation
or template execution ordering is needed.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
for name in ("grid-enrollment", "praxis-gateway"):
    templates = ROOT / "charts/rhai-on-openshift-chart/charts" / name / "templates"
    includes = []
    for path in sorted(templates.rglob("*")):
        if not path.is_file() or path.name.startswith("_"):
            continue
        relative = path.relative_to(templates).as_posix()
        exported = f"{name}.rhoai.{relative}"
        marker = '{{- define "' + exported + '" -}}'
        source = path.read_text()
        suffix = ('{{- end }}\n{{- if .Chart.IsRoot }}\n{{ include "' + exported
                  + '" . }}\n{{- end }}\n')
        if source.startswith(marker):
            if not source.endswith(suffix):
                raise ValueError(f"Malformed existing runtime wrapper: {path}")
            body = source[len(marker): -len(suffix)]
        else:
            body = source
        if re.search(r"{{-?\s*define\s", body):
            raise ValueError(f"Unexpected nested named template in resource: {path}")
        if not source.startswith(marker):
            path.write_text(marker + "\n" + source.rstrip() + "\n{{- end }}\n"
                            '{{- if .Chart.IsRoot }}\n{{ include "' + exported
                            + '" . }}\n{{- end }}\n')
        # A chart test stays wrapped, so it never renders as a dependency, and stays out of
        # the parent's resources. Standalone installs keep it through the .Chart.IsRoot include.
        if path.suffix == ".yaml" and "tests" not in path.relative_to(templates).parts:
            includes.append('{{- $resource := include "' + exported + '" . | trim -}}\n'
                            '{{- if $resource }}\n---\n{{ $resource }}\n{{ end }}\n')
    (templates / "_rhoai-runtime.tpl").write_text(
        '{{/* Generated by scripts/adapt-ai-grid-charts.py; do not edit. */}}\n'
        '{{- define "' + name + '.rhoai.resources" -}}\n'
        + ''.join(includes) + '{{- end }}\n')

# Keep payload image overrides reproducible when charts are re-vendored. These
# downstream helpers consume full image references from the parent operator.
for name, helpers in {
    "grid-enrollment": {
        "image": "RELATED_IMAGE_ODH_PRAXIS_AI_GRID_ENROLLMENT_IMAGE",
        "dbImage": "RELATED_IMAGE_ODH_PRAXIS_AI_GRID_POSTGRES_IMAGE",
    },
    "praxis-gateway": {
        "image": "RELATED_IMAGE_ODH_PRAXIS_AI_GRID_GATEWAY_IMAGE",
        "overlaySyncImage": "RELATED_IMAGE_ODH_PRAXIS_AI_GRID_OVERLAY_SYNC_IMAGE",
    },
}.items():
    path = ROOT / "charts/rhai-on-openshift-chart/charts" / name / "templates/_helpers.tpl"
    source = path.read_text()
    for helper, variable in helpers.items():
        start = source.index('{{- define "' + name + '.' + helper + '" -}}')
        end = source.find('\n{{/*', start)
        if end < 0:
            end = len(source)
        body = source[start:end]
        if f'include "{name}.relatedImage"' in body:
            continue
        opening, remainder = body.split('\n', 1)
        last_end = remainder.rfind('{{- end }}')
        if last_end < 0:
            raise ValueError(f"Cannot wrap image helper {name}.{helper}")
        wrapped = (opening + '\n{{- $image := include "' + name + '.relatedImage" '
                   '(dict "root" . "name" "' + variable + '") -}}\n'
                   '{{- if $image -}}\n{{- $image -}}\n{{- else -}}\n'
                   + remainder[:last_end] + '{{- end }}\n' + remainder[last_end:])
        source = source[:start] + wrapped + source[end:]
    marker = '{{- define "' + name + '.relatedImage" -}}'
    if marker not in source:
        source += ('\n{{/* Full image references injected by downstream payloads. */}}\n'
                   + marker + '\n{{- range (.root.Values.global | default dict).relatedImages -}}\n'
                   '{{- if eq .name $.name -}}\n'
                   '{{- required (printf "%s requires a nonempty value" $.name) .value -}}\n'
                   '{{- end -}}\n{{- end -}}\n{{- end -}}\n')
    if name == "praxis-gateway" and '{{- $override := include "praxis-gateway.relatedImage"' not in source:
        source = source.replace(
            '{{- $auto := and (eq $e "auto")',
            '{{- $override := include "praxis-gateway.relatedImage" '
            '(dict "root" . "name" "RELATED_IMAGE_ODH_PRAXIS_AI_GRID_GATEWAY_IMAGE") -}}\n'
            '{{- $auto := and (eq $e "auto") (not $override)')
    path.write_text(source)
