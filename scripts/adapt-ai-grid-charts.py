#!/usr/bin/env python3
"""Expose vendored runtime templates for profile-aware rendering by the parent.

Standalone installs still render normally. When used as dependencies, resources
are emitted only by the parent's management-state gate. No shared Values mutation
or template execution ordering is needed.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
for name in ("grid-enrollment", "praxis-gateway"):
    templates = ROOT / "charts/rhai-on-openshift-chart/charts" / name / "templates"
    includes = []
    for path in sorted(templates.rglob("*")):
        if not path.is_file() or path.name.startswith("_"):
            continue
        relative = path.relative_to(templates).as_posix()
        exported = f"{name}.rhoai.{relative}"
        marker = '{{- define "' + exported + '" -}}'
        source = path.read_text()
        suffix = ('{{- end }}\n{{- if .Chart.IsRoot }}\n{{ include "' + exported
                  + '" . }}\n{{- end }}\n')
        if source.startswith(marker):
            if not source.endswith(suffix):
                raise ValueError(f"Malformed existing runtime wrapper: {path}")
            body = source[len(marker): -len(suffix)]
        else:
            body = source
        if re.search(r"{{-?\s*define\s", body):
            raise ValueError(f"Unexpected nested named template in resource: {path}")
        if not source.startswith(marker):
            path.write_text(marker + "\n" + source.rstrip() + "\n{{- end }}\n"
                            '{{- if .Chart.IsRoot }}\n{{ include "' + exported
                            + '" . }}\n{{- end }}\n')
        if path.suffix == ".yaml":
            includes.append('{{- $resource := include "' + exported + '" . | trim -}}\n'
                            '{{- if $resource }}\n---\n{{ $resource }}\n{{ end }}\n')
    (templates / "_rhoai-runtime.tpl").write_text(
        '{{/* Generated by scripts/adapt-ai-grid-charts.py; do not edit. */}}\n'
        '{{- define "' + name + '.rhoai.resources" -}}\n'
        + ''.join(includes) + '{{- end }}\n')
